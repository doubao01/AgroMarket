-- 16. 短信验证码不再存明文
-- ---------------------------------------------------------------
-- 原实现把 6 位验证码明文写进 sys_sms_code.code。验证码 10 分钟有效, 但
-- 攻击者拿到库(或拿到只读副本、备份、DBA 顺手一看)就能在有效期内直接登录
-- 任意手机号 —— 短信验证码是登录凭据, 不该以可用形态落库。
-- 现改为存 HMAC-SHA256(密钥取 Jwt:SecretKey) 的十六进制摘要: 校验时比对摘要。
-- 6 位数字只有 100 万种可能, 裸哈希可秒级穷举, 必须带服务端密钥才有意义。
--
-- 注意: 迁移前已入库的明文验证码无法再通过校验, 但它们最长 10 分钟即过期,
-- 无需清理; 升级期正在登录的用户重发一次即可。
USE agro_market;

ALTER TABLE sys_sms_code
  MODIFY COLUMN code VARCHAR(64) NOT NULL COMMENT '验证码 HMAC-SHA256 摘要(不存明文)';
